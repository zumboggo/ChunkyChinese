import {test,expect} from '@playwright/test'
for(const language of ['Chinese','English','bilingual'])test(`prepares ${language} audio, plays offline and resumes the story`,async({page,context})=>{
 test.setTimeout(120000)
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.locator('.featured-episode').getByRole('button',{name:/Play \/ resume episode/}).click()
 await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 await page.locator('.episode-settings>summary').click()
 const popup=page.locator('.encounter-controls')
 await popup.getByRole('group',{name:'Number of encounters'}).getByRole('button',{name:'1',exact:true}).click()
 if(language!=='Chinese')await popup.getByRole('checkbox',{name:'Spoken English',exact:true}).check()
 if(language==='English')await popup.getByRole('checkbox',{name:'Spoken Chinese',exact:true}).uncheck()
 for(const name of ['Chinese characters','Pinyin','English text'])await popup.getByRole('checkbox',{name,exact:true}).uncheck()
 await popup.getByText('Playback options',{exact:true}).click()
 await popup.getByLabel('Story choices',{exact:true}).selectOption('automatic')
 await popup.getByRole('button',{name:'Prepare pocket listening',exact:true}).click()
 const player=page.getByLabel('Pocket audio player',{exact:true})
 await expect(player).toBeVisible({timeout:90000})
 await expect(page.getByText('Ready. Tap Play, then lock your phone.',{exact:true})).toBeVisible()
 await expect(page.locator('.pocket-audio .episode-line')).toHaveCount(0)
 await page.keyboard.press('b')
 await expect(player).toHaveJSProperty('currentTime',0)
 await page.keyboard.press('x')
 await expect.poll(()=>player.evaluate((el:HTMLAudioElement)=>el.currentTime)).toBeGreaterThan(0)
 await page.keyboard.press('b')
 await expect(player).toHaveJSProperty('currentTime',0)
 await expect(player).toHaveJSProperty('paused',true)
 await context.setOffline(true)
 const result=await player.evaluate(async(el:HTMLAudioElement)=>{
  await el.play();el.currentTime=5
  await new Promise(r=>setTimeout(r,300))
  return {duration:el.duration,time:el.currentTime,paused:el.paused,metadata:navigator.mediaSession.metadata?.artist}
 })
 expect(result.duration).toBeGreaterThan(10)
 expect(result.time).toBeGreaterThan(5)
 expect(result.paused).toBe(false)
 expect(result.metadata).toBe('Chunky Chinese')
 await page.screenshot({path:`.local/design/pocket-audio-${language}.png`,fullPage:true})
 await page.getByRole('button',{name:'Return to story',exact:true}).click()
 await expect(player).toHaveCount(0)
 await expect(page.locator('.episode-settings>summary')).toBeVisible()
})
