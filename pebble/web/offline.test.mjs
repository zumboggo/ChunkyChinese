import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:390,height:844}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:5188/pebble-reader.html');
await page.evaluate(async()=>{await navigator.serviceWorker.register('./service-worker.js');await navigator.serviceWorker.ready;});
await page.reload();
await page.locator('#save').click();
await page.getByRole('status').filter({hasText:'All three episodes saved'}).waitFor();
await context.setOffline(true);
await page.reload();
assert.equal(await page.locator('#episode option').count(),3);
await page.selectOption('#episode','supportive-13');
assert.ok(await page.locator('.pinyin').textContent());
await page.locator('#next').click();
const text=await page.locator('.pinyin').textContent();
await page.reload();
assert.equal(await page.locator('.pinyin').textContent(),text);
await page.screenshot({path:'../output/pebble-phone-offline.png',fullPage:true});
console.log('Offline reload, episode switching, and bookmark restoration passed');
await browser.close();
