import {test,expect} from '@playwright/test'

test('compact cinema keeps the scene visible and controls accessible',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByText('Practice & demonstrations',{exact:true}).click()
 await page.getByRole('button',{name:'Play demonstration',exact:true}).click()
 await page.emulateMedia({reducedMotion:'reduce'})
 const controls=page.locator('.episode-settings>summary')
 await expect(controls).toHaveText('Controls ⌄')
 await expect(page.getByRole('button',{name:'Audio: Chinese',exact:true})).toBeHidden()
 await expect(page.getByRole('button',{name:'Restart episode',exact:true})).toBeHidden()
 const stage=await page.locator('.story-stage').boundingBox()
 expect(stage?.y).toBeLessThan(180)
 await controls.click()
 const pinyin=page.getByRole('button',{name:'Text: Pinyin',exact:true})
 const before=await pinyin.getAttribute('aria-pressed')
 await pinyin.click()
 await expect(pinyin).toHaveAttribute('aria-pressed',before==='true'?'false':'true')
 await page.getByRole('button',{name:'Audio Mode',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Audio Mode',exact:true})).toBeVisible()
 await page.keyboard.press('Escape')
 await controls.focus()
 await page.keyboard.press('Escape')
 await expect(page.locator('.episode-settings')).not.toHaveAttribute('open','')
 await expect(controls).toBeFocused()
 await page.getByLabel('Episode options',{exact:true}).click()
 await expect(page.getByRole('button',{name:'Restart episode',exact:true})).toBeVisible()
 await page.keyboard.press('Escape')
 await expect(page.getByRole('button',{name:'Restart episode',exact:true})).toBeHidden()
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await expect(page.locator('.episode-line')).toContainText('别怕')
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await expect(page.getByRole('button',{name:'Choose story',exact:false})).toBeVisible()
})
