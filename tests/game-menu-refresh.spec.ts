import {test,expect} from '@playwright/test'
test('compact library retains selection, settings, tools and playback',async({page},info)=>{
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await expect(page.getByLabel('Find an episode',{exact:true})).toBeHidden()
 await expect(page.getByRole('button',{name:'Create episode',exact:true})).toBeHidden()
 await page.getByRole('button',{name:'Choose story: Super Supportive',exact:true}).click()
 await page.getByLabel('Episode',{exact:true}).selectOption({index:0})
 await page.getByLabel('Find an episode',{exact:true}).fill('no-match-xyz')
 await expect(page.getByRole('heading',{name:'No matching episodes',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Clear search',exact:true}).click()
 await page.getByRole('button',{name:'Done',exact:true}).click()
 await page.getByRole('button',{name:'Game settings',exact:true}).click()
 await page.getByLabel('Game text size',{exact:true}).selectOption('1')
 await page.getByRole('button',{name:'Game settings',exact:true}).click()
 await page.locator('.library-toolbox>summary').click()
 await page.locator('.episode-downloads>summary').click()
 await page.getByRole('button',{name:'Select this series only'}).click()
 await expect(page.locator('.episode-downloads input').first()).toBeChecked()
 await page.locator('.library-toolbox>summary').click()
 await page.reload();await page.getByRole('button',{name:'Game',exact:true}).click()
 await expect(page.locator('.featured-episode')).toContainText('Someone Who Answers')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`../output/game-menu-refresh/implemented-${info.project.name}.png`,fullPage:true})
 await page.getByRole('button',{name:'Pebble episodes',exact:true}).click()
 await expect(page.getByTitle('Pebble episode reader')).toBeVisible()
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await expect(page.getByRole('button',{name:'Accept',exact:true})).toBeVisible()
})
