import {selectSettings} from './helpers/settings'
import {test,expect} from '@playwright/test'

test('Reader compact mode also halves Game text and keeps common lines on one small screen',async({page},info)=>{
 await page.setViewportSize({width:640,height:480})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await page.getByRole('button',{name:'Settings',exact:true}).first().click()
 await selectSettings(page,'Reader')
 const toggle=page.getByRole('checkbox',{name:/Compact text for small screens/})
 if(!await toggle.isChecked())await toggle.check()
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByText('Practice & demonstrations',{exact:true}).click()
 await page.getByRole('button',{name:'Play demonstration',exact:true}).click()
 const game=page.getByRole('region',{name:'Game',exact:true})
 await expect(game).toHaveClass(/game-compact-text/)
 await expect(game.locator('.animated-story')).toBeVisible()
 expect(await game.evaluate(el=>getComputedStyle(el).getPropertyValue('--game-text-scale').trim())).toBe('0.5')
 await page.locator('.episode-settings>summary').click()
 await page.getByRole('group',{name:'Number of encounters'}).getByRole('button',{name:'1',exact:true}).click()
 await page.locator('.episode-settings>summary').click()
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 const chinese=page.locator('.episode-line strong').first()
 await expect(chinese).toBeVisible()
 expect(await chinese.evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeCloseTo(13.2,1)
 for(const width of [640,1280]){
  await page.setViewportSize({width,height:width===640?480:960})
  await expect(chinese).toBeVisible()
  expect(await game.evaluate(el=>el.scrollHeight<=el.clientHeight+1)).toBe(true)
  expect(await game.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
  await page.screenshot({path:`.local/design/game-compact-${width}-${info.project.name.replaceAll(' ','-')}.png`,fullPage:true})
 }
 await page.setViewportSize({width:640,height:480})
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await expect(page.locator('.episode-line strong').first()).toBeVisible()
 expect(await game.evaluate(el=>el.scrollHeight<=el.clientHeight+1)).toBe(true)
})
