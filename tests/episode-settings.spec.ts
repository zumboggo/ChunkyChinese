import {test,expect} from '@playwright/test'

test('episode settings stay tucked away and persist between episodes and reloads',async({page},info)=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.locator('.episode-strip button').filter({hasText:/^01/}).click()
 await page.getByRole('button',{name:'Restart episode',exact:true}).click()
 await expect(page.locator('.episode-intro,.animated-story')).toBeVisible()
 if(await page.getByRole('button',{name:'Skip intro →',exact:true}).isVisible())await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 const settings=page.locator('.episode-settings')
 await expect(settings).toBeVisible()
 await expect(page.getByRole('button',{name:/Pause scene motion/})).toHaveCount(0)
 await expect(page.getByLabel('Game text size')).toBeHidden()
 await page.screenshot({path:'.local/design/episode-settings-'+info.project.name+'.png',fullPage:true})
 await settings.locator('summary').click()
 await page.getByLabel('Game text size').selectOption('2')
 await page.getByRole('checkbox',{name:'English',exact:true}).click()
 await page.getByLabel('Voice volume',{exact:true}).fill('0.4')
 await page.getByLabel('Sound captions',{exact:true}).check()
 await page.getByLabel('Effects volume',{exact:true}).fill('0.2')
 await page.getByLabel('Pause scene motion',{exact:true}).check()
 await expect(page.locator('.story-stage')).toHaveAttribute('data-idle-paused','true')
 await page.getByLabel('Reduce motion',{exact:true}).check()
 await settings.locator('summary').focus()
 await page.keyboard.press('Escape')
 await expect(page.getByLabel('Game text size')).toBeHidden()
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.locator('.episode-strip button').filter({hasText:/^02/}).click()
 await page.getByRole('button',{name:'Restart episode',exact:true}).click()
 await expect(page.locator('.episode-intro,.animated-story')).toBeVisible()
 if(await page.getByRole('button',{name:'Skip intro →',exact:true}).isVisible())await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 await settings.locator('summary').click()
 await expect(page.getByLabel('Game text size')).toHaveValue('2')
 await expect(page.getByRole('checkbox',{name:'English',exact:true})).not.toBeChecked()
 await expect(page.getByLabel('Voice volume',{exact:true})).toHaveValue('0.4')
 await expect(page.getByLabel('Effects volume',{exact:true})).toHaveValue('0.2')
 await expect(page.getByLabel('Sound captions',{exact:true})).toBeChecked()
 await expect(page.getByLabel('Reduce motion',{exact:true})).toBeChecked()
 await expect(page.getByLabel('Pause scene motion',{exact:true})).toBeChecked()
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await page.reload()
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByRole('button',{name:'Resume',exact:true}).click()
 await settings.locator('summary').click()
 await expect(page.getByLabel('Voice volume',{exact:true})).toHaveValue('0.4')
 await expect(page.getByLabel('Game text size')).toHaveValue('2')
})
