import {test,expect} from '@playwright/test'
for(const episode of [1,2,3])test(`episode ${episode} has a controllable two-paragraph opening`,async({page},info)=>{
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByLabel('Book',{exact:true}).selectOption('jedi')
 const option=await page.getByLabel('Episode',{exact:true}).locator('option').filter({hasText:new RegExp(`^0${episode} ·`)}).getAttribute('value')
 await page.getByLabel('Episode',{exact:true}).selectOption(option!)
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await page.getByRole('button',{name:'Accept',exact:true}).click()
 const context=page.getByRole('region',{name:'Opening context'})
 await expect(context).toBeVisible();await expect(context.locator('p')).toHaveCount(2)
 await expect(page.locator('video')).toHaveCount(0)
 await page.keyboard.press('2');await expect(page.getByRole('button',{name:'Resume crawl'})).toBeVisible()
 await page.screenshot({path:info.outputPath(`episode-${episode}-crawl.png`),fullPage:true})
 await page.keyboard.press('2');await expect(page.getByRole('button',{name:'Pause crawl'})).toBeVisible()
 await page.keyboard.press('3');await expect(context).toHaveClass(/is-static/)
 await page.screenshot({path:info.outputPath(`episode-${episode}-full.png`),fullPage:true})
 await page.keyboard.press('1');await expect(page.locator('video')).toBeVisible()
 await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 await expect(page.locator('.episode-line')).toBeVisible()
 await page.getByRole('button',{name:'Restart intro',exact:true}).click()
 await expect(context).toBeVisible()
 await page.emulateMedia({reducedMotion:'reduce'});await expect(context).toHaveClass(/is-static/)
 await expect(context.locator('p')).toHaveCount(2)
})
