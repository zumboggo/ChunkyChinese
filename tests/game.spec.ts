test('Settings uploads a playable episode; Resume and seven text sizes survive reload',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Settings',exact:true}).first().click()
 await page.getByLabel('Episode ZIP or JSON',{exact:true}).setInputFiles('stories/animated/gate-in-the-mist.json')
 await expect(page.getByRole('status').filter({hasText:'is ready in The Game.'})).toBeVisible()
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await expect(page.getByRole('button',{name:'Resume',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:/Daily Life Small moments/}).click()
 const downloadPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'Export episode ZIP',exact:true}).click()
 const zip=await downloadPromise
 const buffer=await readFile((await zip.path())!)
 await page.getByRole('button',{name:'Settings',exact:true}).first().click()
 await page.getByLabel('Episode ZIP or JSON',{exact:true}).setInputFiles({name:'episode.zip',mimeType:'application/zip',buffer})
 await expect(page.getByRole('status').filter({hasText:'is ready in The Game.'})).toBeVisible()
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByRole('button',{name:/Daily Life Small moments/}).click()
 await expect(page.locator('.episode-strip button')).toHaveCount(1)
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).first().click()
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 const line=await page.locator('.chinese-line').innerText()
 const before=await page.locator('.chinese-line').evaluate(el=>parseFloat(getComputedStyle(el).fontSize))
 const sizes=page.getByLabel('Game text size',{exact:true})
 await expect(sizes.locator('option')).toHaveCount(7)
 await sizes.selectOption('6')
 expect(await page.locator('.chinese-line').evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThan(before*1.8)
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.reload()
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await expect(page.getByLabel('Game text size',{exact:true})).toHaveValue('6')
 await page.getByRole('button',{name:'Resume',exact:true}).click()
 await expect(page.locator('.chinese-line')).toHaveText(line)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})

