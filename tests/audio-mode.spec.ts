import {test,expect,type Page} from '@playwright/test'

async function start(page:Page){
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.addInitScript(()=>{
  // Deterministic audio completions let the test check sequence and cancellation,
  // without depending on installed voices or a sound device on the test machine.
  Math.random=()=>0
  const events:string[]=[]
  Object.assign(window,{audioModeEvents:events})
  const timers=new WeakMap<HTMLMediaElement,ReturnType<typeof setTimeout>>()
  HTMLMediaElement.prototype.play=function(){
   if(this.src.startsWith('data:audio/'))events.push('chinese')
   timers.set(this,setTimeout(()=>this.dispatchEvent(new Event('ended')),160))
   return Promise.resolve()
  }
  HTMLMediaElement.prototype.pause=function(){clearTimeout(timers.get(this))}
  let speechTimer:ReturnType<typeof setTimeout>
  Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>[],speak:(utterance:SpeechSynthesisUtterance)=>{events.push(utterance.lang+':'+utterance.text);speechTimer=setTimeout(()=>utterance.dispatchEvent(new Event('end')),30)},cancel:()=>clearTimeout(speechTimer)}})
 })
 await page.goto('/')
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByRole('button',{name:'Restart episode',exact:true}).waitFor()
 if(await page.getByLabel('Episode',{exact:true}).count())await page.getByLabel('Episode',{exact:true}).selectOption({index:0})
 else await page.locator('.episode-strip button').filter({hasText:/^01/}).click()
 await page.getByRole('button',{name:'Restart episode',exact:true}).click()
 await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
}

test('Audio Mode popup saves preferences across episodes and reloads',async({page},info)=>{
 await start(page)
 await page.getByRole('button',{name:'Audio Mode',exact:true}).click()
 const popup=page.getByRole('dialog',{name:'Audio Mode',exact:true})
 await expect(popup).toBeVisible()
 await expect(popup.getByLabel('Pause before English',{exact:true})).toHaveValue('3')
 await popup.getByLabel('Spoken language',{exact:true}).selectOption('bilingual')
 await popup.getByLabel('Pause before English',{exact:true}).selectOption('0')
 await popup.getByRole('button',{name:'Hide all text',exact:true}).click()
 await popup.getByLabel('Story choices',{exact:true}).selectOption('automatic')
 await expect(popup.getByLabel('Automatic choice delay',{exact:true})).toHaveValue('0')
 await page.screenshot({path:'.local/design/audio-mode-'+info.project.name+'.png',fullPage:true})
 await page.keyboard.press('Escape')
 await expect(popup).not.toBeVisible()
 await expect(page.locator('.episode-line strong,.episode-line .reader-interlinear-pinyin,.episode-line .reader-interlinear-gloss')).toHaveCount(0)
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.getByRole('button',{name:'Restart episode',exact:true}).waitFor()
 if(await page.getByLabel('Episode',{exact:true}).count())await page.getByLabel('Episode',{exact:true}).selectOption({index:1})
 else await page.locator('.episode-strip button').filter({hasText:/^02/}).click()
 await page.getByRole('button',{name:'Restart episode',exact:true}).click()
 if(await page.getByRole('button',{name:'Skip intro →',exact:true}).isVisible())await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 await page.getByRole('button',{name:'Audio Mode',exact:true}).click()
 await expect(popup.getByLabel('Spoken language',{exact:true})).toHaveValue('bilingual')
 await expect(popup.getByLabel('Characters',{exact:true})).not.toBeChecked()
 await expect(popup.getByLabel('Pinyin',{exact:true})).not.toBeChecked()
 await expect(popup.getByLabel('English',{exact:true})).not.toBeChecked()
 await popup.getByRole('button',{name:'Close',exact:true}).click()
 await page.reload()
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByRole('button',{name:'Resume',exact:true}).click()
 await page.getByRole('button',{name:'Audio Mode',exact:true}).click()
 await expect(popup.getByLabel('Story choices',{exact:true})).toHaveValue('automatic')
 await expect(popup.getByLabel('Pause before English',{exact:true})).toHaveValue('0')
})

test('bilingual playback waits for English, pauses safely and handles choices hands free',async({page})=>{
 test.setTimeout(60000)
 await start(page)
 const original=await page.locator('.episode-line').innerText()
 await page.getByRole('button',{name:'Audio Mode',exact:true}).click()
 const popup=page.getByRole('dialog',{name:'Audio Mode',exact:true})
 await popup.getByLabel('Spoken language',{exact:true}).selectOption('bilingual')
 await popup.getByLabel('Pause before English',{exact:true}).selectOption('3')
 await popup.getByRole('button',{name:'Start Audio Mode',exact:true}).click()
 await expect(page.getByRole('button',{name:'Pause Audio Mode',exact:true})).toBeVisible()
 await expect.poll(()=>page.evaluate(()=>((window as unknown as {audioModeEvents:string[]}).audioModeEvents).length)).toBeGreaterThan(0)
 await expect(page.locator('.episode-line')).toHaveText(original,{useInnerText:true})
 await page.getByRole('button',{name:'Pause Audio Mode',exact:true}).click()
 await page.waitForTimeout(3300)
 expect(await page.evaluate(()=>((window as unknown as {audioModeEvents:string[]}).audioModeEvents).filter(e=>e.startsWith('en-US:')))).toHaveLength(0)
 await expect(page.locator('.episode-line')).toHaveText(original,{useInnerText:true})
 await page.getByRole('button',{name:'Audio Mode',exact:true}).click()
 await popup.getByLabel('Pause before English',{exact:true}).selectOption('0')
 await popup.getByLabel('Story choices',{exact:true}).selectOption('manual')
 await popup.getByRole('button',{name:'Resume Audio Mode',exact:true}).click()
 await expect.poll(()=>page.evaluate(()=>((window as unknown as {audioModeEvents:string[]}).audioModeEvents).some(e=>e.startsWith('en-US:')))).toBe(true)
 await expect(page.getByRole('heading',{name:'What do I do?',exact:true})).toBeVisible({timeout:30000})
 await expect(page.getByText('Choose an option to keep listening.',{exact:true})).toBeVisible({timeout:10000})
 await page.getByRole('button',{name:'Audio Mode',exact:true}).click()
 await popup.getByLabel('Story choices',{exact:true}).selectOption('automatic')
 await popup.getByRole('button',{name:'Resume Audio Mode',exact:true}).click()
 await expect(page.getByRole('heading',{name:'What do I do?',exact:true})).toHaveCount(0,{timeout:10000})
 await expect(page.getByRole('heading',{name:'Scene complete',exact:true})).toBeVisible({timeout:30000})
 await expect(page.getByText('Episode complete',{exact:true})).toBeVisible()
 await expect(page.locator('.story-dialogue [role=status]')).toHaveCount(0)
})
