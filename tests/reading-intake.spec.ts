 await page.getByLabel('Chinese and English text',{exact:true}).fill('Hello.\n你好。')
 await page.getByRole('button',{name:'Add pasted text'}).click()
 await expect(page.getByText(/Line 1 should be Chinese/)).toBeVisible()
