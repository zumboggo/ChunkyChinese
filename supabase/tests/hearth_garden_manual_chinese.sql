BEGIN;
DO $$
declare u uuid:=gen_random_uuid(); other_user uuid:=gen_random_uuid(); d date:=(now() at time zone 'Asia/Shanghai')::date; w date; r jsonb; op jsonb; epoch bigint:=extract(epoch from now())::bigint;
begin
 w:=d-extract(dow from d)::integer;
 insert into auth.users(id) values(u),(other_user);
 insert into public.garden_profiles(user_id,started_at) values(u,now()-interval '30 days'),(other_user,now()-interval '30 days');
 insert into public.review_events(user_id,event_id,event_data,"timestamp") select u,'auto'||i,jsonb_build_object('source','game','type','complete','sessionId','attempt'||i),now() from generate_series(1,6) i;
 op:=jsonb_build_object('id','manual-1','kind','chinese_add','day',d-date '1970-01-01','occurred',epoch);
 r:=public.garden_sync(u,jsonb_build_array(op));
 assert (r#>>'{state,episodeWeekTotal}')::int=7,'combined count';
 assert (r#>>'{state,ge}')::int=1,'manual seventh completion earns Chinese gem';
 assert (r#>>'{state,totalEpisodes}')::int=7,'lifetime count includes manual';
 assert (r#>>'{state,et}')::int=1,'today completion';
 assert jsonb_array_length(r#>'{state,manualChineseDays}')=7,'seven daily manual counts';
 r:=public.garden_sync(u,jsonb_build_array(op));assert (r#>>'{state,episodeWeekTotal}')::int=7,'retry deduplication';
 op:=op||'{"id":"manual-2"}'::jsonb;r:=public.garden_sync(u,jsonb_build_array(op));assert (r#>>'{state,episodeWeekTotal}')::int=8,'manual overflow';
 assert (r#>>'{state,ge}')::int=1,'only one gem for week';
 op:=op||'{"id":"undo-1","kind":"chinese_undo_day"}'::jsonb;r:=public.garden_sync(u,jsonb_build_array(op));assert (r#>>'{state,episodeWeekTotal}')::int=7,'undo manual';
 op:=op||'{"id":"undo-2"}'::jsonb;r:=public.garden_sync(u,jsonb_build_array(op));assert (r#>>'{state,episodeWeekTotal}')::int=6,'second undo manual';
 assert (r#>>'{state,ge}')::int=1,'earned gem retained';
 op:=op||'{"id":"undo-empty"}'::jsonb;r:=public.garden_sync(u,jsonb_build_array(op));assert jsonb_array_length(r->'rejected')=1,'cannot undo automatic events';
 assert (select count(*) from public.review_events where user_id=u)=6,'automatic study history unchanged';
 op:=jsonb_build_object('id','backdate','kind','chinese_add','day',w-date '1970-01-01','occurred',epoch);
 r:=public.garden_sync(u,jsonb_build_array(op));assert (r#>>'{state,episodeWeekTotal}')::int=7,'backdate within week';
 assert (r#>>'{state,manualChineseDays,0}')::int=1,'backdated day counts';
 assert jsonb_array_length(r#>'{state,manualChineseHistory}')=1,'backup history';
 op:=jsonb_build_object('id','offline-old-week','kind','chinese_add','day',d-7-date '1970-01-01','occurred',epoch-604800);
 r:=public.garden_sync(u,jsonb_build_array(op));assert (r#>>'{state,episodeWeekTotal}')::int=7,'old offline event not credited to current week';
 assert (r#>>'{state,totalEpisodes}')::int=8,'old offline entry retained';
 op:=jsonb_build_object('id','invalid-future','kind','chinese_add','day',d+1-date '1970-01-01','occurred',epoch);
 r:=public.garden_sync(u,jsonb_build_array(op));assert jsonb_array_length(r->'rejected')=1,'future credit rejected';
 op:=op||jsonb_build_object('id','invalid-week','day',w-1-date '1970-01-01');r:=public.garden_sync(u,jsonb_build_array(op));assert jsonb_array_length(r->'rejected')=1,'arbitrary previous-week credit rejected';
 r:=public.garden_sync(other_user,'[]');assert (r#>>'{state,totalEpisodes}')::int=0,'owner isolation';
 assert not has_table_privilege('authenticated','public.garden_chinese','SELECT'),'private manual table';
 assert not has_function_privilege('anon','public.garden_completion_days(uuid,timestamptz)','EXECUTE'),'private helper';
end $$;
select 'PASS: manual add, undo, retries, mixed totals, gems, overflow, backdating, offline rollover, backup and isolation' test_result;
ROLLBACK;
