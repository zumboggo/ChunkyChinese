 await expect(page.getByText('Temporary walk is ready in Reading.')).toBeVisible()
 await page.getByRole('button',{name:'Close text creator'}).click()
 await page.getByLabel('Category',{exact:true}).selectOption('Legendary Moonlight Sculptor')
 await page.getByRole('button',{name:'Short',exact:true}).click()
 const temporary=page.locator('.reading-library-book',{hasText:'Temporary walk'})
 await expect(temporary).toContainText('Temporary')
 await temporary.getByRole('button',{name:'Start',exact:true}).click()
 await expect(page.locator('.reader-translation')).toContainText('I want to read.')
 await page.getByRole('button',{name:'Library',exact:true}).click()
 await page.reload()
 await openLibrary(page)
 await expect(page.locator('.reading-library-book',{hasText:'Temporary walk'})).toHaveCount(0)
