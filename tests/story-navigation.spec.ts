import {test,expect} from '@playwright/test';
test('left arrow restores beats, choices and saved position without passing the beginning',async({page})=>{
 await page.goto('/tests/fixtures/story-navigation.html');
 const line=page.locator('.story-dialogue');
 await expect(line).toContainText('Opening beat.');
 await page.keyboard.press('ArrowLeft');
 await expect(page.getByTestId('progress')).toHaveText(JSON.stringify({steps:[],quizzes:[],seed:19}));
 await page.keyboard.press('ArrowRight');
 await expect(line).toContainText('Take the left path.');
 await expect(page.getByRole('button',{name:/^(Choose option 1|Take the left path\.)$/})).toBeEnabled();
 await page.keyboard.press('1');
 await expect(line).toContainText('Left path beat.');
 await page.keyboard.press('ArrowLeft');
 await expect(line).toContainText('Take the right path.');
 await page.keyboard.press('2');
 await expect(line).toContainText('Right path beat.');
 await expect(page.getByRole('button',{name:'Continue →',exact:true})).toBeEnabled();
 await page.keyboard.press('ArrowRight');
 await expect(line).toContainText('Scene complete');
 await page.keyboard.press('ArrowLeft');
 await expect(line).toContainText('Right path beat.');
 await expect(page.getByTestId('progress')).toHaveText(JSON.stringify({steps:[null,'right'],quizzes:[],seed:19}));
 await page.reload();
 await expect(line).toContainText('Right path beat.');
 await page.locator('.episode-settings summary').click();
 await page.keyboard.press('ArrowLeft');
 await expect(line).toContainText('Right path beat.');
 await page.getByLabel('Voice volume',{exact:true}).focus();
 await page.keyboard.press('ArrowLeft');
 await expect(line).toContainText('Right path beat.');
 await page.keyboard.press('Escape');
 await line.click({position:{x:5,y:5}});
 await page.keyboard.press('Alt+ArrowLeft');
 await expect(line).toContainText('Right path beat.');
 await page.keyboard.press('ArrowLeft');
 await expect(line).toContainText('Take the left path.');
 await page.keyboard.press('ArrowLeft');
 await expect(line).toContainText('Opening beat.');
});
