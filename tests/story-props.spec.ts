import {test,expect} from '@playwright/test'
test('visible props persist, actions finish, and reduced motion shows projectiles',async({page},info)=>{
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByText('Practice & demonstrations',{exact:true}).click()
 const card=page.locator('article').filter({has:page.getByRole('heading',{name:'Props & fantasy actions · Rehearsal',exact:true})})
 await card.getByRole('button',{name:'Restart episode',exact:true}).click()
 const next=page.getByRole('button',{name:'Continue →',exact:true})
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect(page.locator('[data-prop=phone]')).toHaveCount(1)
 await page.screenshot({path:'.local/props-phone-'+info.project.name+'.png',fullPage:true})
 await next.click();await expect(page.locator('[data-prop=phone]')).toHaveCount(1)
 await next.click();await expect(page.locator('[data-prop=phone]')).toHaveCount(0)
 await next.click();await expect(page.locator('[data-prop=sword]')).toHaveCount(1)
 await page.emulateMedia({reducedMotion:'no-preference'})
 for(let i=0;i<3;i++){await next.click();await expect(next).toBeEnabled({timeout:5000})}
 await next.click();await expect(page.locator('[data-prop=bow]')).toHaveCount(1)
 await page.emulateMedia({reducedMotion:'reduce'});await next.click()
 await expect(page.getByRole('img',{name:'Arrow flight',exact:true})).toBeVisible()
 await page.screenshot({path:'.local/props-bow-'+info.project.name+'.png',fullPage:true})
 await page.getByRole('button',{name:'← Story library',exact:true}).click();await page.getByText('Practice & demonstrations',{exact:true}).click();await card.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await expect(page.locator('[data-prop=bow]')).toHaveCount(1)
 await next.click();await expect(page.locator('[data-prop=bow]')).toHaveCount(0)
 await next.click();await expect(page.getByRole('img',{name:'Magic beam',exact:true})).toBeVisible()
 await page.screenshot({path:'.local/props-magic-'+info.project.name+'.png',fullPage:true})
 await next.click();await expect(page.getByRole('img',{name:'Magic beam',exact:true})).toHaveCount(0)
 await next.click();await expect(page.getByRole('heading',{name:'Scene complete'})).toBeVisible()
})
test('arrow and beam animate once and disappear before Continue',async({page},info)=>{
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByText('Practice & demonstrations',{exact:true}).click()
 const card=page.locator('article').filter({has:page.getByRole('heading',{name:'Props & fantasy actions · Rehearsal',exact:true})})
 await card.getByRole('button',{name:'Restart episode',exact:true}).click()
 await page.emulateMedia({reducedMotion:'reduce'})
 const next=page.getByRole('button',{name:'Continue →',exact:true})
 for(let i=0;i<7;i++)await next.click()
 await page.emulateMedia({reducedMotion:'no-preference'});await next.click()
 await expect(page.locator('.story-projectile.active')).toBeVisible()
 await page.waitForFunction(()=>{const e=document.querySelector('.story-projectile.active .story-arrow');return e&&Number(getComputedStyle(e).opacity)>.5})
 await page.screenshot({path:'.local/props-arrow-motion-'+info.project.name+'.png',fullPage:true})
 await expect(next).toBeEnabled({timeout:5000});await expect(page.locator('.story-projectile')).toHaveClass(/settled/)
 await next.click();await next.click()
 await page.waitForFunction(()=>{const e=document.querySelector('.story-projectile.active .story-beam');return e&&Number(getComputedStyle(e).opacity)>.5})
 await page.screenshot({path:'.local/props-beam-motion-'+info.project.name+'.png',fullPage:true})
 await expect(next).toBeEnabled({timeout:5000});await expect(page.locator('.story-projectile')).toHaveClass(/settled/)
})
