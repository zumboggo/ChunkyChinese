import {test,expect} from '@playwright/test'
test('Jedi book, acceptance, intro and saved story survive reload',async({page},info)=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByLabel('Book',{exact:true}).selectOption('jedi')
 await expect(page.locator('.featured-episode h2')).toHaveText('Who Is Speaking?')
 await expect(page.locator('.episode-cover')).toHaveAttribute('src',/jedi\/series-cover\.jpg$/)
 await expect(page.locator('.episode-cover')).toHaveJSProperty('complete',true)
 await page.screenshot({path:info.outputPath('series-cover.png'),fullPage:true})
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await expect(page.getByRole('button',{name:'Accept',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Accept',exact:true}).click()
 const video=page.locator('.episode-intro video');await expect(video).toHaveJSProperty('readyState',4)
 expect(await video.evaluate(v=>(v as HTMLVideoElement).muted)).toBe(false)
 expect(await video.evaluate(v=>(v as HTMLVideoElement).paused)).toBe(true)
 expect(await video.evaluate(v=>(v as HTMLVideoElement).duration)).toBeCloseTo(9,0)
 await page.screenshot({path:info.outputPath('intro.png'),fullPage:true})
 await page.getByRole('button',{name:'Play intro with sound',exact:true}).click()
 await video.evaluate(v=>{(v as HTMLVideoElement).currentTime=8.8})
 await expect(page.locator('.episode-line')).toBeVisible()
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 const line=await page.locator('.episode-line').textContent()
 await page.getByRole('button',{name:'Restart intro',exact:true}).click()
 await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 await expect(page.locator('.episode-line')).toHaveText(line!)
 await page.screenshot({path:info.outputPath('reading.png'),fullPage:true})
 await page.reload();await page.getByRole('button',{name:'Game',exact:true}).click()
 await expect(page.getByLabel('Book',{exact:true})).toHaveValue('jedi')
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await expect(page.locator('.episode-line')).toHaveText(line!)
 await expect(page.getByRole('button',{name:'Accept',exact:true})).toHaveCount(0)
})
