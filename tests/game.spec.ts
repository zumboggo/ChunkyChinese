import {test,expect} from '@playwright/test'
test('native story, Mandarin audio, branch callback and resume',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByText('Practice & demonstrations',{exact:true}).click()
 await page.getByRole('button',{name:'Play demonstration'}).click()
 await expect(page.locator('.story-stage svg')).toHaveCount(2)
 await expect(page.locator('iframe')).toHaveCount(0)
 await page.getByLabel('Reduced motion',{exact:true}).check()
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await expect(page.locator('.chinese-line')).toHaveText('别怕。我和你一起走。')
 await expect(page.locator('.story-dialogue .pinyin')).toContainText('bié')
 await page.getByRole('button',{name:'Play audio',exact:true}).click()
 await expect(page.locator('svg.puppet-speaking')).toHaveCount(1)
 await expect(page.getByText('Do not be afraid. I will go with you.',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await expect(page.locator('svg.puppet-speaking')).toHaveCount(0)
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await page.getByRole('button',{name:'I try to slip past the keeper.',exact:true}).click()
 await expect(page.getByText('The keeper lunges. Lan blocks, and both step back. Nobody is hurt.',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.getByText('Practice & demonstrations',{exact:true}).click()
 await page.getByRole('button',{name:'Play demonstration'}).click()
 await expect(page.getByText('The keeper lunges. Lan blocks, and both step back. Nobody is hurt.',{exact:true})).toBeVisible()
 for(let i=0;i<3;i++)await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await expect(page.locator('.chinese-line')).toHaveText('下次先说话，好吗？')
 for(let i=0;i<3;i++)await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Scene complete'})).toBeVisible()
})
test('shared studio previews branches and publishes immutable local package',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByRole('button',{name:'Create episode',exact:true}).click()
 await page.getByText('Choices and callbacks',{exact:true}).click()
 await page.getByRole('combobox',{name:/Choice to compare/}).selectOption('approach')
 await page.getByRole('button',{name:'Preview outcomes side by side'}).click()
 await expect(page.locator('details').filter({has:page.getByText('Choices and callbacks',{exact:true})}).locator('.animated-story')).toHaveCount(2)
 await page.getByText('Choices and callbacks',{exact:true}).click()
 await page.getByLabel('Episode title',{exact:true}).fill('My native adventure')
 await page.getByRole('button',{name:'Publish to my library',exact:true}).click()
 await page.getByRole('button',{name:/Daily Life Small moments/}).click()
 await expect(page.getByRole('heading',{name:'My native adventure',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Edit a copy',exact:true}).click()
 await page.getByLabel('Episode title',{exact:true}).fill('Changed draft')
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.getByRole('button',{name:/Daily Life Small moments/}).click()
 await expect(page.getByRole('heading',{name:'My native adventure',exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Changed draft',exact:true})).toHaveCount(0)
})
test('published package opens offline from its embedded assets',async({page,context})=>{
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByRole('button',{name:'Create episode',exact:true}).click()
 await page.getByRole('button',{name:'Publish to my library',exact:true}).click()
 await page.getByRole('button',{name:/Daily Life Small moments/}).click()
 await expect(page.getByRole('button',{name:'Play / resume episode',exact:true})).toBeVisible()
 await context.setOffline(true)
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await expect(page.locator('.story-stage svg')).toHaveCount(2)
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await page.getByRole('button',{name:'Play audio',exact:true}).click()
 await expect(page.locator('svg.puppet-speaking')).toHaveCount(1)
})
