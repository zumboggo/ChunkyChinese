import {test,expect,type Page} from '@playwright/test'
async function start(page:Page){
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.locator('.episode-strip button').filter({hasText:/^01/}).click()
 await page.getByRole('button',{name:'Restart episode',exact:true}).click()
 await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
}
async function defaults(page:Page,chinese:boolean,pinyin:boolean,english:boolean){
 const settings=page.locator('.episode-settings')
 await settings.locator('summary').click()
 await settings.getByRole('checkbox',{name:'Characters',exact:true}).setChecked(chinese)
 await settings.getByRole('checkbox',{name:'Pinyin',exact:true}).setChecked(pinyin)
 await settings.getByRole('checkbox',{name:'English',exact:true}).setChecked(english)
 await settings.locator('summary').click()
}
test('all eight default combinations reveal only the tapped chunk and reset on the next line',async({page},info)=>{
 await start(page)
 const first=page.locator('.episode-line .reader-interlinear-chunk').first()
 for(let mask=0;mask<8;mask++){
  await defaults(page,Boolean(mask&1),Boolean(mask&2),Boolean(mask&4))
  await expect(first.locator('strong')).toHaveCount(mask&1?1:0)
  await expect(first.locator('.reader-interlinear-pinyin')).toHaveCount(mask&2?1:0)
  await expect(first.locator('.reader-interlinear-gloss')).toHaveCount(mask&4?1:0)
  if(mask!==7){
   await first.click()
   await expect(first.locator('strong')).toHaveCount(1)
   await expect(first.locator('.reader-interlinear-pinyin')).toHaveCount(1)
   await expect(first.locator('.reader-interlinear-gloss')).toHaveCount(1)
   await expect(page.locator('.episode-line .reader-interlinear-chunk').nth(1).locator('.reader-interlinear-gloss')).toHaveCount(mask&4?1:0)
   await first.click()
   await expect(first.locator('.reader-interlinear-gloss')).toHaveCount(mask&4?1:0)
  }
 }
 await defaults(page,true,false,false)
 await first.focus()
 await page.keyboard.press('Enter')
 await expect(first).toHaveAttribute('aria-expanded','true')
 await page.screenshot({path:'.local/design/chunk-reveal-'+info.project.name+'.png',fullPage:true})
 await page.keyboard.press('Escape')
 await expect(first).toHaveAttribute('aria-expanded','false')
 await first.click()
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 await expect(page.locator('.episode-line .reader-interlinear-gloss')).toHaveCount(0)
 for(let i=0;i<40&&!await page.locator('.episode-choice-card').count();i++)await page.getByRole('button',{name:'Continue →',exact:true}).click()
 const choice=page.locator('.episode-choice-card').first()
 await expect(choice).toBeVisible()
 await choice.locator('.episode-chunk').first().click()
 await expect(page.getByRole('heading',{name:'What do I do?',exact:true})).toBeVisible()
 await expect(choice.locator('.reader-interlinear-gloss').first()).toBeVisible()
 await page.getByRole('button',{name:'Choose option 1',exact:true}).click()
 await expect(page.getByRole('heading',{name:'What do I do?',exact:true})).toHaveCount(0)
})
test('replay opening preserves position, resume restores it, and completion offers the next episode',async({page},info)=>{
 await start(page)
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 const text=await page.locator('.episode-line').innerText()
 await page.locator('.episode-settings>summary').click()
 await page.getByRole('button',{name:'Replay opening',exact:true}).click()
 await expect(page.getByRole('region',{name:'Episode introduction'})).toBeVisible()
 await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 await expect(page.locator('.episode-line')).toBeVisible()
 expect(await page.locator('.episode-line').innerText()).toBe(text)
 await page.reload()
 await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByRole('button',{name:'Resume',exact:true}).click()
 await expect(page.locator('.episode-line')).toBeVisible()
 expect(await page.locator('.episode-line').innerText()).toBe(text)
 await expect(page.locator('.episode-intro')).toHaveCount(0)
 for(let i=0;i<80;i++){
  if(await page.getByRole('heading',{name:'Scene complete',exact:true}).count())break
  const choices=page.locator('.episode-choice')
  if(await choices.count())await choices.first().click()
  else await page.getByRole('button',{name:'Continue →',exact:true}).click()
 }
 await expect(page.getByText('A phone call interrupts the evening. What could be so urgent?',{exact:true})).toBeVisible()
 await page.screenshot({path:'.local/design/episode-handoff-'+info.project.name+'.png',fullPage:true})
 await page.getByRole('button',{name:'Continue to Episode 2 →',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Moonlight Sculptor 02 · An Impossible Number',exact:true})).toBeVisible()
})
