import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
const catalog=JSON.parse(readFileSync('public/stories/animated/catalog.json','utf8'))
test('library scales beyond 100 episodes without downloading every lesson',async({page},info)=>{
 const downloads:string[]=[];page.on('request',r=>{if(/\/stories\/animated\/(moonlight|wind)-[^/]+\.json/.test(r.url()))downloads.push(r.url())})
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await expect(page.getByLabel('Book',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Episode',{exact:true}).locator('option')).toHaveCount(catalog.filter((e:{category:string})=>e.category==='lms').length)
 expect(downloads).toEqual([])
 await page.getByLabel('Find an episode',{exact:true}).fill('26')
 await expect(page.getByLabel('Episode',{exact:true}).locator('option')).toHaveCount(1)
 await page.getByLabel('Book',{exact:true}).selectOption('name-of-the-wind')
 await expect(page.getByRole('heading',{name:'A Story Before Supper',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await page.getByRole('button',{name:'Accept',exact:true}).click()
 if(await page.locator('.episode-intro').count())await page.getByRole('button',{name:'Skip intro →',exact:true}).click()
 await expect(page.locator('.episode-line')).toContainText('晚上')
 expect(downloads).toHaveLength(1)
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.evaluate(async()=>{
  const db=await new Promise<IDBDatabase>((ok,no)=>{const q=indexedDB.open('ChunkyChineseStory2',1);q.onsuccess=()=>ok(q.result);q.onerror=()=>no(q.error)})
  const keys=await new Promise<IDBValidKey[]>((ok,no)=>{const q=db.transaction('records').objectStore('records').getAllKeys();q.onsuccess=()=>ok(q.result);q.onerror=()=>no(q.error)})
  const prefix=String(keys.find(k=>String(k).endsWith('latest-played'))).replace(/latest-played$/,'')
  if(!prefix.startsWith('story2:'))throw Error('Missing account scope')
  await new Promise<void>((ok,no)=>{const tx=db.transaction('records','readwrite');for(let i=100;i<260;i++)tx.objectStore('records').put({id:'test-'+i,category:'lms',episode:i,created:'2026-10-26',pack:{format:2,profile:'chinese',title:`Moonlight Sculptor ${i} · Library fixture ${i}`,description:'Navigation scale test',script:'story 2\nI: 你好。\nend',assets:{characters:{},backgrounds:{}},quiz:[]}},prefix+'release:test-'+i);tx.oncomplete=()=>ok();tx.onerror=()=>no(tx.error)})
  db.close()
 })
 await page.reload();await page.getByRole('button',{name:'Game',exact:true}).click();await page.getByLabel('Book',{exact:true}).selectOption('lms')
 await expect(page.getByLabel('Episode',{exact:true}).locator('option')).toHaveCount(catalog.filter((e:{category:string})=>e.category==='lms').length+160)
 await page.getByLabel('Find an episode',{exact:true}).fill('259')
 await page.getByLabel('Episode',{exact:true}).selectOption('test-259')
 await expect(page.getByRole('heading',{name:'Library fixture 259',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Next →',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'← Previous',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Library fixture 258',exact:true})).toBeVisible()
 await page.getByLabel('Find an episode',{exact:true}).fill('no matching title')
 await expect(page.getByRole('heading',{name:'No matching episodes',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Clear search',exact:true}).click()
 await page.getByLabel('Book',{exact:true}).selectOption('name-of-the-wind')
 await expect(page.getByRole('button',{name:'Next →',exact:true})).toBeDisabled()
 await expect(page.locator('body')).toHaveJSProperty('scrollWidth',await page.locator('body').evaluate(e=>e.clientWidth))
 await page.screenshot({path:'.local/notw/library-'+info.project.name+'.png',fullPage:true})
})
