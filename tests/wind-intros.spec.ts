import {test,expect} from '@playwright/test'
for(const episode of [1,2])test(`Wind ${episode} accepted intro plays and resumes into the lesson`,async({page},info)=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/');await page.getByRole('button',{name:'Game',exact:true}).click()
 await page.getByLabel('Book',{exact:true}).selectOption('name-of-the-wind')
 await page.getByLabel('Episode',{exact:true}).selectOption(`wind-0${episode}-v1`)
 await page.getByRole('button',{name:'Restart episode',exact:true}).click()
 await page.getByRole('button',{name:'Accept',exact:true}).click()
 const video=page.locator('.episode-intro video')
 await expect.poll(()=>video.evaluate(e=>Math.round((e as HTMLVideoElement).duration))).toBe(episode===1?9:6)
 await expect(video).toHaveJSProperty('muted',false)
 await page.getByRole('button',{name:'Play intro with sound',exact:true}).click()
 await expect.poll(()=>video.evaluate(e=>(e as HTMLVideoElement).currentTime),{timeout:6000}).toBeGreaterThan(3.2)
 await expect(video).toHaveJSProperty('paused',false)
 await page.screenshot({path:`.local/notw/wind-${episode}-intro-${info.project.name}.png`,fullPage:true})
 await expect(page.locator('.episode-line')).toBeVisible({timeout:12000})
 await page.getByRole('button',{name:'Continue →',exact:true}).click()
 const line=await page.locator('.episode-line').textContent()
 await page.getByRole('button',{name:'← Story library',exact:true}).click()
 await page.getByRole('button',{name:'Play / resume episode',exact:true}).click()
 await expect(page.locator('.episode-line')).toHaveText(line!)
 await expect(page.locator('.episode-intro')).toHaveCount(0)
})
